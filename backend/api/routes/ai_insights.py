class StrategyRequest(BaseModel):
    risk_appetite: str = Field(default="medium", pattern="^(low|medium|high)$")
    horizon: str = Field(default="medium", pattern="^(short|medium|long)$")
    storage: str = Field(default="limited", pattern="^(none|limited|good)$")
    state: str | None = None


@router.post("/strategy")
def post_strategy(req: StrategyRequest) -> dict:
    """Decision-intelligence recommendations from user constraints."""
    state = None
    if req.state:
        try:
            state = validate_state(req.state)
        except ValueError as exc:
            raise HTTPException(status_code=422, detail=str(exc))
    return executive.strategy(_peers(), {
        "risk_appetite": req.risk_appetite, "horizon": req.horizon,
        "storage": req.storage, "state": state,
    })


