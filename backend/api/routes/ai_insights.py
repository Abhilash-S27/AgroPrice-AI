@router.get("/compare")
def get_ai_compare(
    crops: list[str] = Query(..., min_length=2, max_length=6),
) -> dict:
    """Multi-crop AI comparison from the cross-crop analytics cache."""
    try:
        wanted = [validate_crop(c) for c in crops]
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc))

    peers = _peers()
    if not peers:
        raise HTTPException(
            status_code=503,
            detail="Cross-crop analytics cache is still warming — retry shortly.",
        )
    records = [p for p in peers if p["crop"] in wanted]
    return narrator.compare_crops(records)
